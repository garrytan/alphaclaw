// Fallback for reason values outside the canonical enum (old/new servers):
// claims nothing it can't know.
const kFallbackCopy = {
  cause: "This file is not being injected (cause not recognized by this UI version).",
  short: "Open Drift Doctor for details; run /context on the agent.",
};

export const getHardeningReasonCopy = (reason, { managed = false } = {}) => {
  // String()-coerce at the boundary: null/number/object inputs land on the
  // fallback instead of throwing or matching an Object.prototype key.
  const key = typeof reason === "string" ? reason : String(reason ?? "");
  const entry = Object.prototype.hasOwnProperty.call(kHardeningReasonCopy, key)
    ? kHardeningReasonCopy[key]
    : null;
  if (!entry) return { ...kFallbackCopy };
  return {
    cause: entry.cause,
    short: (managed && entry.managedShort) || entry.short,
  };
};
