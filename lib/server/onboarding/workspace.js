// AlphaClaw's prompt hardening ships as TWO bootstrap extras, both named
// AGENTS.md (a valid extras basename on every supported OpenClaw line, while
// a TOOLS.md extra is silently rejected on 2026.8.1+):
// - hooks/bootstrap/AGENTS.md: the rules (safety and git first), then the
//   harness, the machine profile and the agent-admin stanza. About 5k chars.
// - hooks/bootstrap/reference/AGENTS.md: operator data that grows with the
//   install (Google accounts, the topic registry), rendered to stay under
//   kReferenceTargetRatio of the per-file cap, with the topic rows capped at
//   kTopicInlineMaxChars. An operator may take this one out of the extras
//   (see reconcileBootstrapExtraConfig).
// A third file, hooks/bootstrap/reference/setup-ui.md (the Setup UI tab map),
// is written next to the reference file and never injected: the rules file
// points the agent at it.
// OpenClaw caps each extra separately (bootstrapMaxChars, 20k by default) and
// injects them in config order after the root files, so the rules come first
// and the data starves first. A file still over its cap is reported once per
// condition through onOverCap (the server wires a watchdog event), naming the
// sections OpenClaw will cut (see docs/designs/openclaw-context-contract.md).
// Migration ordering per sync:
// (1) write both files atomically — hardening is never absent;
// (2) reconcile the openclaw.json hook entry (diff-before-write, preserves
//     user-added paths, drops only AlphaClaw's legacy TOOLS.md path);
// (3) delete the legacy AlphaClaw-owned hooks/bootstrap/TOOLS.md — but only
//     when step (2) succeeded, since a failed reconcile may leave the config
//     still referencing the legacy path.
// A crash between steps (or a skipped step 3) leaves at worst a harmless
// stale TOOLS.md (duplicate tools guidance consuming budget) that self-heals
// on the next sync (every boot). Failures at any stage surface through
// onFailure (the server wires a watchdog event) — never console-only.
const syncBootstrapPromptFiles = ({
  fs,
  workspaceDir,
  baseUrl,
  onFailure = null,
  onOverCap = null,
  openclawDir = OPENCLAW_DIR,
  rootDir = kRootDir,
  envFilePath = ENV_FILE_PATH,
  gitWriterCommand = process.env.ALPHACLAW_GIT_WRITER_COMMAND,
}) => {
  const reportFailure = (stage, error) => {
    console.error(`[onboard] Bootstrap prompt sync ${stage} failed: ${error.message}`);
    try {
      onFailure?.(stage, error);
    } catch {
      // failure reporting must never break the sync itself
    }
  };
  try {
    const setupUiUrl = resolveSetupUiUrl(baseUrl);

    const toolsTemplate = fs.readFileSync(
      path.join(kSetupDir, "core-prompts", "TOOLS.md"),
      "utf8",
    );
    const agentsTemplate = fs.readFileSync(
      path.join(kSetupDir, "core-prompts", "AGENTS.md"),
      "utf8",
    );
    // The Setup UI map is optional: a failed read must never cost the agent
    // its rules, so it is reported and skipped.
    let setupUiTemplate = null;
    try {
      setupUiTemplate = fs.readFileSync(
        path.join(kSetupDir, "core-prompts", "setup-ui.md"),
        "utf8",
      );
    } catch (e) {
      reportFailure("setup-ui-template", e);
    }
    const telegramEnabled = isTelegramWorkspaceEnabled(fs);
    const topicCreateActionActive = telegramEnabled && isTopicCreateActionActive(fs);
    const googleAccountsSection = renderGoogleAccountsMarkdown(fs);
    const machineProfileSection = renderMachineProfileMarkdown(fs);
    // Rendered through ONE var map applied to BOTH templates (#121) — the
    // agents template used to be concatenated raw, so a token added to
    // core-prompts/AGENTS.md would have shipped to the agent literally.
    const promptVars = buildPromptTemplateVars({
      setupUiUrl,
      openclawDir,
      rootDir,
      envFilePath,
      gitWriterCommand,
    });
    const renderedAgentsTemplate = renderPromptTemplate(
      agentsTemplate,
      promptVars,
    );
    const setupUiContent =
      setupUiTemplate === null ? null : renderPromptTemplate(setupUiTemplate, promptVars);
    // Agent-admin pointer stanza — only when the skill is actually installed
    // (never advertise before live).
    let adminStanza = "";
    try {
      const { renderToolsStanza } = require("../agent-admin/skill");
      adminStanza = renderToolsStanza({ fs, openclawDir: OPENCLAW_DIR });
    } catch {}
    const buildRulesContent = (agentId) => {
      let harnessContent = renderPromptTemplate(toolsTemplate, {
        ...promptVars,
        TELEGRAM_THREAD_RULE: telegramEnabled ? renderTelegramThreadRule(agentId) : "",
      });
      // The machine section opens with its own blank line; trimming first
      // keeps it to one (OpenClaw collapses a double one when it injects).
      if (machineProfileSection) harnessContent = harnessContent.trimEnd() + machineProfileSection;
      harnessContent += adminStanza;
      return `${renderedAgentsTemplate.trimEnd()}\n\n${harnessContent}`;
    };

    const openclawConfig =
      readOpenclawConfig({ fsModule: fs, openclawDir: OPENCLAW_DIR, fallback: {} }) || {};
    const resolveFileCap = (agentId) =>
      resolveAgentBootstrapBudget(
        openclawConfig,
        agentId || "main",
        "bootstrapMaxChars",
        kDoctorBootstrapMaxChars,
      );

    const buildReferenceContent = ({ agentId = "", capChars }) => {
      const fixedContent = `${kReferenceHeader}${googleAccountsSection}`;
      const topicSection = renderTopicRegistryMarkdown({
        includeSyncGuidance: telegramEnabled,
        telegramEnabled,
        topicCreateActionActive,
        agentId,
        maxChars: Math.max(
          0,
          Math.floor(capChars * kReferenceTargetRatio) - fixedContent.length,
        ),
        maxRowChars: kTopicInlineMaxChars,
      });
      return `${fixedContent}${topicSection}\n`;
    };

    const checkFileCap = (targetDir, relativePath, content, capChars) => {
      const key = path.join(targetDir, relativePath);
      const sections = findTruncatedSections(content, capChars);
      if (sections.length === 0) {
        lastOverCapSignatures.delete(key);
        return;
      }
      const chars = content.trimEnd().length;
      console.error(
        `[onboard] ${relativePath} is ${chars} chars, over OpenClaw's ${capChars}-char per-file ` +
          `injection cap; OpenClaw will cut: ${sections.join(", ")}`,
      );
      const signature = `${capChars}|${sections.join("|")}`;
      if (!onOverCap || lastOverCapSignatures.get(key) === signature) return;
      lastOverCapSignatures.set(key, signature);
      try {
        onOverCap({ workspaceDir: targetDir, path: relativePath, chars, capChars, sections });
      } catch {
        // reporting must never break the sync itself
      }
    };

    const writeToWorkspace = (targetDir, agentId = "", { reference = true, rest = true } = {}) => {
      const capChars = resolveFileCap(agentId);
      const files = [
        ...(rest ? [[kAlphaclawRulesBootstrapPath, buildRulesContent(agentId), true]] : []),
        ...(reference
          ? [[kAlphaclawReferenceBootstrapPath, buildReferenceContent({ agentId, capChars }), true]]
          : []),
        ...(rest && setupUiContent !== null ? [[kAlphaclawSetupUiReferencePath, setupUiContent, false]] : []),
      ];
      for (const [relativePath, content, injected] of files) {
        const filePath = path.join(targetDir, ...relativePath.split("/"));
        fs.mkdirSync(path.dirname(filePath), { recursive: true });
        // Atomic write (E4.8): openclaw reads this at session bootstrap; a torn
        // file would feed the agent a truncated prompt.
        if (writeFileAtomicIfChanged(filePath, content, { fsModule: fs })) {
          noteGeneratedFileChanged({ filePath, openclawDir, fallbackName: relativePath });
        }
        if (injected) checkFileCap(targetDir, relativePath, content, capChars);
      }
    };

    const removeLegacyToolsFile = (targetDir) => {
      // Derived from the same constant that governs the config reconcile so
      // the file deletion and the entry removal can never drift apart.
      for (const legacyRelativePath of kLegacyAlphaclawBootstrapExtraPaths) {
        const legacyPath = path.join(targetDir, ...legacyRelativePath.split("/"));
        try {
          if (fs.existsSync(legacyPath)) fs.unlinkSync(legacyPath);
        } catch (e) {
          reportFailure("legacy-tools-delete", e);
        }
      }
    };

    // Read before this sync writes it: a reference file already on disk proves
    // an AlphaClaw that injects it (v0.10.117+) ran here, so a config without
    // its path was edited, not written by an older AlphaClaw.
    let referenceFileSeen = false;
    try {
      referenceFileSeen = fs.existsSync(
        path.join(workspaceDir, ...kAlphaclawReferenceBootstrapPath.split("/")),
      );
    } catch {}

    const syncedWorkspaces = [workspaceDir];
    writeToWorkspace(workspaceDir, "", { reference: referenceFileSeen });

    const otherWorkspaces = resolveAllAgentWorkspaces(fs).filter(
      (entry) => path.resolve(entry.workspace) !== path.resolve(workspaceDir),
    );
    for (const entry of otherWorkspaces) {
      try {
        writeToWorkspace(entry.workspace, entry.agentId);
        syncedWorkspaces.push(entry.workspace);
      } catch (e) {
        reportFailure(`workspace-sync:${entry.workspace}`, e);
      }
    }

    const configReconciled = reconcileBootstrapExtraConfig({
      fs,
      reportFailure,
      referenceFileSeen,
    });
    if (configReconciled && !referenceFileSeen) {
      writeToWorkspace(workspaceDir, "", { rest: false });
    }

    // Delete only after the config reconcile succeeded (write→reconcile→
    // delete): on a reconcile failure openclaw.json may still reference
    // hooks/bootstrap/TOOLS.md, and deleting the file it points at would
    // break the injection. The kept stale TOOLS.md self-heals on the next
    // boot sync (every boot), same as a crash between steps.
    if (configReconciled) {
      for (const syncedWorkspace of syncedWorkspaces) {
        removeLegacyToolsFile(syncedWorkspace);
      }
    }

    console.log("[onboard] Bootstrap prompt files synced");
  } catch (e) {
    reportFailure("merge-write", e);
  }
};

// Boot-path hook-entry migration: onboarding's ensureManagedConfigShell only
// runs for fresh installs — already-onboarded installs migrate here, on every
// resync. Diff-before-write keeps this a no-op once migrated (no needless
// openclaw.json churn). Returns true on success (including the intentional
// no-op paths), false on a caught failure — the caller must NOT delete the
// legacy TOOLS.md when the config that may still reference it wasn't
// reconciled.
//
// Operator opt-out (ALPH-58 decision 3): resolveBootstrapExtraEntryPlan
// decides from the live config, inside the locked mutate. A deliberate
// removal of the reference path is persisted once as
// alphaclaw.json promptFiles.reference = { enabled: false, detectedAt, by },
// and later syncs read that flag. The rules path is always put back, with one
// watchdog event and a promptFiles.rulesRestoredAt stamp for the Doctor card.
const reconcileBootstrapExtraConfig = ({ fs, reportFailure, referenceFileSeen = false }) => {
  try {
    const config = readOpenclawConfig({
      fsModule: fs,
      openclawDir: OPENCLAW_DIR,
      fallback: null,
    });
    // No parseable openclaw.json: a MISSING file means not onboarded —
    // creation belongs to onboarding's ensureManagedConfigShell, nothing to
    // reconcile (true). A PRESENT file our strict parser cannot read (legal
    // JSON5/${ENV}/$include upstream) may still reference
    // hooks/bootstrap/TOOLS.md, so reporting it reconciled would let the
    // caller delete the only hardening injection. Same doctrine as the
    // doctor's config_unreadable state: not ours to judge — skip the delete
    // (false); self-heals if the config ever becomes strict-JSON readable.
    if (!config || typeof config !== "object") {
      const configPath = resolveOpenclawConfigPath({ openclawDir: OPENCLAW_DIR });
      if (!fs.existsSync(configPath)) return true;
      console.warn(
        "[onboard] openclaw.json exists but is not parseable as strict JSON " +
          "(JSON5/env/include?) — skipping hook-entry reconcile and legacy " +
          "TOOLS.md cleanup for this sync.",
      );
      return false;
    }
    // Full self-heal, not just path migration: a deleted entry or a flipped
    // hooks.internal.enabled means the flagship hardening is silently never
    // injected — the boot resync is the layer that repairs it. The entry's
    // `patterns`/`files` aliases fold into `paths` (the hook's non-empty
    // `paths` short-circuits the aliases completely); the alias keys stay
    // untouched.
    const { referenceDisabled } = readPromptFilesState({ fsModule: fs, openclawDir: OPENCLAW_DIR });
    const isEntryCurrent = (candidate, paths) => {
      const entry = candidate?.hooks?.internal?.entries?.["bootstrap-extra-files"];
      const currentPaths = Array.isArray(entry?.paths)
        ? entry.paths.map((value) => String(value || ""))
        : [];
      return (
        candidate?.hooks?.internal?.enabled === true &&
        entry?.enabled === true &&
        currentPaths.length === paths.length &&
        currentPaths.every((value, index) => value === paths[index])
      );
    };
    const hasDecision = (plan) =>
      plan.referenceRemoved || plan.referenceReadded || plan.rulesRestored;
    const preview = resolveBootstrapExtraEntryPlan({ config, referenceDisabled, referenceFileSeen });
    if (isEntryCurrent(config, preview.paths) && !hasDecision(preview)) return true;
    let plan = preview;
    updateOpenclawConfig({
      fsModule: fs,
      openclawDir: OPENCLAW_DIR,
      mutate: (liveConfig) => {
        plan = resolveBootstrapExtraEntryPlan({
          config: liveConfig,
          referenceDisabled,
          referenceFileSeen,
        });
        if (isEntryCurrent(liveConfig, plan.paths)) return { skipWrite: true };
        if (!liveConfig.hooks) liveConfig.hooks = {};
        if (!liveConfig.hooks.internal) liveConfig.hooks.internal = {};
        if (!liveConfig.hooks.internal.entries) liveConfig.hooks.internal.entries = {};
        liveConfig.hooks.internal.enabled = true;
        const liveEntry =
          liveConfig.hooks.internal.entries["bootstrap-extra-files"] || {};
        liveConfig.hooks.internal.entries["bootstrap-extra-files"] = {
          ...liveEntry,
          enabled: true,
          paths: plan.paths,
        };
      },
    });
    if (!isEntryCurrent(config, plan.paths)) {
      console.log("[onboard] bootstrap-extra-files hook entry reconciled");
    }
    recordPromptFilesDecision({ fs, plan, reportFailure });
    return true;
  } catch (e) {
    reportFailure("config-reconcile", e);
    return false;
  }
};

// Persists what the locked reconcile decided. A failed alphaclaw.json write
// is reported and retried by the next sync, which sees the same config.
const recordPromptFilesDecision = ({ fs, plan, reportFailure }) => {
  const nowMs = Date.now();
  try {
    if (plan.referenceRemoved) {
      updatePromptFilesState({
        fsModule: fs,
        openclawDir: OPENCLAW_DIR,
        mutate: (promptFiles) => {
          promptFiles.reference = { enabled: false, detectedAt: nowMs, by: "operator-config" };
        },
      });
      console.log(
        `[onboard] ${kAlphaclawReferenceBootstrapPath} was removed from bootstrap-extra-files; ` +
          "keeping it out (re-enable from Drift Doctor)",
      );
      logPromptFilesEvent({
        source: "reference-off",
        status: "ok",
        details: { path: kAlphaclawReferenceBootstrapPath, by: "operator-config" },
      });
    }
    if (plan.referenceReadded) {
      updatePromptFilesState({
        fsModule: fs,
        openclawDir: OPENCLAW_DIR,
        mutate: (promptFiles) => {
          delete promptFiles.reference;
        },
      });
      console.log(
        `[onboard] ${kAlphaclawReferenceBootstrapPath} is back in bootstrap-extra-files; injecting it again`,
      );
    }
    if (plan.rulesRestored) {
      updatePromptFilesState({
        fsModule: fs,
        openclawDir: OPENCLAW_DIR,
        mutate: (promptFiles) => {
          promptFiles.rulesRestoredAt = nowMs;
        },
      });
      console.warn(
        `[onboard] ${kAlphaclawRulesBootstrapPath} was missing from bootstrap-extra-files; restored it ` +
          "(AlphaClaw's safety rules are always injected)",
      );
      logPromptFilesEvent({
        source: "rules-restored",
        status: "warning",
        details: { path: kAlphaclawRulesBootstrapPath },
      });
    }
  } catch (e) {
    reportFailure("prompt-files-flag", e);
  }
};

// Human-only re-enable (POST /api/doctor/prompt-files/reference): put the
// reference path back first, then clear the flag. A crash between the two
// leaves the path listed with the flag set, which the next sync reads as a
// re-add and clears.
const enableBootstrapReference = ({ fs }) => {
  updateOpenclawConfig({
    fsModule: fs,
    openclawDir: OPENCLAW_DIR,
    mutate: (liveConfig) => {
      if (!liveConfig.hooks) liveConfig.hooks = {};
      if (!liveConfig.hooks.internal) liveConfig.hooks.internal = {};
      if (!liveConfig.hooks.internal.entries) liveConfig.hooks.internal.entries = {};
      liveConfig.hooks.internal.enabled = true;
      const liveEntry = liveConfig.hooks.internal.entries["bootstrap-extra-files"] || {};
      liveConfig.hooks.internal.entries["bootstrap-extra-files"] = {
        ...liveEntry,
        enabled: true,
        paths: resolveBootstrapExtraEntryPlan({ config: liveConfig }).paths,
      };
    },
  });
  updatePromptFilesState({
    fsModule: fs,
    openclawDir: OPENCLAW_DIR,
    mutate: (promptFiles) => {
      delete promptFiles.reference;
    },
  });
  console.log(`[onboard] ${kAlphaclawReferenceBootstrapPath} re-enabled by an operator`);
  logPromptFilesEvent({
    source: "reference-on",
    status: "ok",
    details: { path: kAlphaclawReferenceBootstrapPath },
  });
  return readPromptFilesState({ fsModule: fs, openclawDir: OPENCLAW_DIR });
};

const ensureOpenclawRuntimeArtifacts = ({
  fs,
  openclawDir,
  envFilePath = ENV_FILE_PATH,
}) => {
  try {
    const openclawEnvLink = path.join(openclawDir, ".env");
    // A full-root import can promote the repo's committed .env OVER the
    // managed symlink (fix wave F106): a regular file here is a stale
    // raw-secret copy that OpenClaw's dotenv, the hourly git sync and the git
    // shim would keep reading. Move it aside (its approved values were merged
    // into the live .env by the import) and restore the link.
    if (
      typeof fs.lstatSync === "function" &&
      typeof fs.renameSync === "function" &&
      fs.existsSync(envFilePath)
    ) {
      let linkStat = null;
      try {
        linkStat = fs.lstatSync(openclawEnvLink);
      } catch {}
      if (linkStat && !linkStat.isSymbolicLink() && linkStat.isFile()) {
        const asidePath = `${openclawEnvLink}.imported-${Date.now().toString(36)}`;
        fs.renameSync(openclawEnvLink, asidePath);
        console.warn(
          `[alphaclaw] ${openclawEnvLink} was a regular file (imported repo .env) — moved to ${asidePath}; the managed .env link is restored`,
        );
      }
    }
    if (!fs.existsSync(openclawEnvLink) && fs.existsSync(envFilePath)) {
      fs.symlinkSync(envFilePath, openclawEnvLink);
      console.log(`[alphaclaw] Symlinked ${openclawEnvLink} -> ${envFilePath}`);
    }
  } catch (e) {
    console.log(`[alphaclaw] .env symlink skipped: ${e.message}`);
  }

  const gogConfigFile = path.join(openclawDir, "gogcli", "config.json");
  if (!fs.existsSync(gogConfigFile)) {
    // Non-fatal (F008): this was the only throw path in the boot's prompt-file
    // sync, and it aborted the gateway launch when gogcli/ was unwritable.
    try {
      fs.mkdirSync(path.join(openclawDir, "gogcli"), { recursive: true });
    } catch (error) {
      console.log(`[alphaclaw] gogcli dir skipped: ${error.message}`);
      return;
    }
    try {
      execSync("gog auth keyring file", { stdio: "ignore" });
      console.log("[alphaclaw] gog keyring configured (file backend)");
    } catch {}
  }
};

