// AlphaClaw-owned operator data (Google accounts, topic registry) is rendered
// to stay under this share of OpenClaw's per-file cap: the same near-limit
// line the Doctor uses, so a full registry never reads as "near limit".
const kReferenceTargetRatio = kDoctorBootstrapNearLimitRatio;
const kReferenceHeader =
  "# AlphaClaw Workspace Reference\n\n" +
  "Generated by AlphaClaw from its own state and rewritten on every sync; do not edit this file.";

// Last over-cap report per written file, so one condition raises one
// watchdog event instead of one per sync.
const lastOverCapSignatures = new Map();

// Substituted path values are VALIDATED, never mutated (stripping would
// corrupt legal paths): a value with control chars, backticks, or template
// braces is not rendered — the token falls back to the env-var reference,
// which stays true because the gateway always exports OPENCLAW_STATE_DIR /
// OPENCLAW_HOME into the agent's shell.
const isSafePromptTemplateValue = (value) =>
  typeof value === "string" &&
  value.length > 0 &&
  // eslint-disable-next-line no-control-regex
  !/[\u0000-\u001f\u007f`]/.test(value) &&
  !value.includes("{{");

// {{TOKEN}} rendering for BOTH core-prompt templates (#121). Unknown tokens
// are left intact on purpose: a typo'd token stays visible in the rendered
// file instead of silently blanking an agent safety rule (and the shipped
// templates are pinned by a no-`{{`-survives test). A known token whose
// value is the empty string renders as nothing (optional prompt sections).
const renderPromptTemplate = (template, vars) =>
  String(template).replace(/\{\{([A-Z0-9_]+)\}\}/g, (match, tokenName) =>
    Object.prototype.hasOwnProperty.call(vars, tokenName) &&
    typeof vars[tokenName] === "string"
      ? vars[tokenName]
      : match,
  );

const kGitWriterCommandMaxChars = 300;
let lastIgnoredGitWriterCommand = null;

const kPullRule =
  "- Before you start, update only with `git pull --ff-only`. Never run a plain `git pull`, " +
  "`git pull --rebase`, `git merge` or `git rebase` on this repository, and never force push.";
const kInProgressRule =
  "- If you find a merge or rebase already in progress, leave it alone and tell the user.";

const kPlainGitRules = [
  kPullRule,
  "- Commit only the paths you changed (`git commit -- <paths>`), then push.",
  "- If the fast-forward or your push is refused because the histories diverged, stop. Do not merge or " +
    "rebase to reconcile them: tell the user the repository has diverged and leave it to them.",
  kInProgressRule,
].join("\n");

// With a writer, the writer replaces raw commit and push and the
// diverged-history stop: one rule set, never the plain rules with an
// exception appended that contradicts them.
const renderWriterGitRules = (command) =>
  [
    kPullRule,
    `- This repository has a sanctioned writer: commit and push only with \`${command}\`. ` +
      "Never run raw `git commit` or `git push` on this repository.",
    `- If \`git pull --ff-only\` fails, run \`${command}\` instead of stopping.`,
    "- If the writer refuses, stop and tell the user. Never fall back to raw git, a merge, a rebase " +
      "or a force push.",
    kInProgressRule,
  ].join("\n");

// ALPHACLAW_GIT_WRITER_COMMAND: the operator's sanctioned commit-and-push
// command for the workspace repository. Unset renders the plain rules; an
// unsafe or oversized value is never rendered (same validation as
// substituted paths), so the agent keeps the plain fast-forward-only rules.
const renderGitRules = (command) => {
  const value = String(command || "").trim();
  if (!value) return kPlainGitRules;
  if (!isSafePromptTemplateValue(value) || value.length > kGitWriterCommandMaxChars) {
    if (lastIgnoredGitWriterCommand !== value) {
      lastIgnoredGitWriterCommand = value;
      console.warn(
        "[onboard] ALPHACLAW_GIT_WRITER_COMMAND ignored: it must be one line of at most " +
          `${kGitWriterCommandMaxChars} characters without backticks or {{.`,
      );
    }
    return kPlainGitRules;
  }
  return renderWriterGitRules(value);
};

const buildPromptTemplateVars = ({
  setupUiUrl,
  openclawDir,
  rootDir,
  envFilePath,
  gitWriterCommand,
}) => ({
  SETUP_UI_URL: setupUiUrl,
  STATE_DIR: isSafePromptTemplateValue(openclawDir)
    ? openclawDir
    : "$OPENCLAW_STATE_DIR",
  ROOT_DIR: isSafePromptTemplateValue(rootDir) ? rootDir : "$OPENCLAW_HOME",
  ENV_FILE: isSafePromptTemplateValue(envFilePath)
    ? envFilePath
    : "$OPENCLAW_HOME/.env",
  GIT_RULES: renderGitRules(gitWriterCommand),
});

// Configured-origin chain shared with lib/server/public-origin.js (PR 8a):
// an explicit base URL wins, then the platform's domain variables, then the
// localhost default. Never request-derived — this feeds persisted values.
const resolveSetupUiUrl = (baseUrl) => {
  const normalizedBaseUrl = String(baseUrl || "").trim().replace(/\/+$/, "");
  if (normalizedBaseUrl) return normalizedBaseUrl;
  return resolveConfiguredOrigin() || "http://localhost:3000";
};

// Single assembly point for TOOLS.md: template + topic registry.
// Idempotent — always rebuilds from source so deploys never clobber topic data.
const isTelegramWorkspaceEnabled = (fs) => {
  try {
    const configPath = `${OPENCLAW_DIR}/openclaw.json`;
    const cfg = JSON.parse(fs.readFileSync(configPath, "utf8"));
    const telegramConfig = cfg.channels?.telegram || {};
    const topLevelGroupCount = Object.keys(telegramConfig.groups || {}).length;
    if (topLevelGroupCount > 0) return true;
    const accounts =
      telegramConfig.accounts && typeof telegramConfig.accounts === "object"
        ? telegramConfig.accounts
        : {};
    for (const accountConfig of Object.values(accounts)) {
      if (Object.keys(accountConfig?.groups || {}).length > 0) return true;
    }
    return false;
  } catch {
    return false;
  }
};

// Accounts gog lists but AlphaClaw's state does not (added with `gog auth
// add` outside the Setup UI) come from the gog-accounts.js cache, so the
// render never spawns gog.
const renderGoogleAccountsMarkdown = (fs) => {
  try {
    const { getDetectedGogAccounts } = require("../gog-accounts");
    const googleStatePath = `${OPENCLAW_DIR}/gogcli/state.json`;
    const state = readGoogleState({ fs, statePath: googleStatePath });
    const accounts = Array.isArray(state.accounts) ? state.accounts : [];
    const managedKeys = new Set(
      accounts.map((account) => {
        const client = String(account.client || "default").trim() || "default";
        return `${client}\n${String(account.email || "").trim().toLowerCase()}`;
      }),
    );
    const outsideAccounts = getDetectedGogAccounts().filter(
      (account) => !managedKeys.has(`${account.client}\n${account.email.toLowerCase()}`),
    );
    const outsideSection = outsideAccounts.length
      ? "Also stored in gog (use `--client <client> --account <email>` for gog commands):\n\n" +
        outsideAccounts
          .map(
            (account) =>
              `- ${account.email} (configured in gog outside the Setup UI; client: ${account.client})`,
          )
          .join("\n") +
        "\n"
      : "";
    let section = "\n\n## Available Google Accounts\n\n";
    if (!accounts.length) {
      section += outsideSection || "No Google accounts are currently configured.\n";
      return section;
    }
    section +=
      "Configured in AlphaClaw (use `--client <client> --account <email>` for gog commands):\n\n";
    section += accounts
      .map((account) => {
        const email = String(account.email || "").trim() || "(unknown email)";
        const client = String(account.client || "default").trim() || "default";
        const personal = account.personal ? "personal" : "company";
        const auth = account.authenticated ? "authenticated" : "awaiting sign-in";
        const services = Array.isArray(account.services) ? account.services.join(", ") : "";
        const metaParts = [
          `type: ${personal}`,
          `client: ${client}`,
          `status: ${auth}`,
          services ? `services: ${services}` : null,
        ].filter(Boolean);
        return `- ${email} (${metaParts.join("; ")})`;
      })
      .join("\n");
    section += "\n";
    if (outsideSection) section += `\n${outsideSection}`;
    return section;
  } catch {
    return "";
  }
};

// ≤500 chars, injected into every agent session: capacity only (tier, RAM,
// vCPU, GPU) plus the applied concurrency cap — live usage stays behind the
// watchdog API. Regenerated on boot via doSyncPromptFiles, so resizes are
// reflected automatically. Fail-open: any error renders nothing.
const renderMachineProfileMarkdown = (fs) => {
  try {
    const { getMachineProfile } = require("../machine-profile");
    const { getAgentConcurrencyCap } = require("../autotune");
    const { sanitizeLabel } = require("../utils/sanitize-label");
    const profile = getMachineProfile();
    const limitBytes = profile?.memory?.limitBytes;
    if (!Number.isFinite(limitBytes)) return "";
    const memoryGb = (limitBytes / (1024 * 1024 * 1024)).toFixed(1);
    const cores = profile.cpu?.cores ?? "?";
    // GPU name is external nvidia-smi output → sanitize before it reaches a prompt.
    const gpuName = profile.gpu?.present
      ? sanitizeLabel(profile.gpu.devices?.[0]?.name || profile.gpu.vendor || "GPU")
      : null;
    let section = "\n\n## Machine Resources\n\n";
    section += `- Capacity: ${profile.tier} tier — ${memoryGb} GB RAM, ${cores} vCPU`;
    if (gpuName) section += `, GPU: ${gpuName}`;
    section += "\n";
    // null when autotune is off or suppressed — say nothing rather than a stale cap.
    const cap = getAgentConcurrencyCap({ fsModule: fs });
    if (cap != null) {
      section += `- Agent concurrency cap (autotune): ${cap}\n`;
    }
    section +=
      "- Live usage: ask an admin, or run `alphaclaw admin GET /api/watchdog/resources` if agent administration is enabled.\n";
    return section;
  } catch {
    return "";
  }
};

const resolveAllAgentWorkspaces = (fs) => {
  try {
    const configPath = path.join(OPENCLAW_DIR, "openclaw.json");
    const cfg = JSON.parse(fs.readFileSync(configPath, "utf8"));
    const agents =
      cfg.agents && typeof cfg.agents === "object" && !Array.isArray(cfg.agents)
        ? cfg.agents
        : {};
    // Mirror upstream roster precedence (dist readAgentRosterProperty): a
    // present `agents.entries` keyed map (key = agent id, value = entry) wins
    // over the `agents.list` array — property presence short-circuits, even
    // when both exist.
    let rosterEntries;
    if (agents.entries !== undefined) {
      const entriesMap =
        agents.entries &&
        typeof agents.entries === "object" &&
        !Array.isArray(agents.entries)
          ? agents.entries
          : {};
      rosterEntries = Object.entries(entriesMap).map(([agentId, entry]) => ({
        id: agentId,
        workspace: entry?.workspace,
      }));
    } else {
      rosterEntries = Array.isArray(agents.list) ? agents.list : [];
    }
    return rosterEntries
      .map((entry) => {
        const agentId = String(entry?.id || "").trim();
        const workspace = String(entry?.workspace || "").trim();
        if (!agentId || !workspace) return null;
        return {
          agentId,
          workspace,
        };
      })
      .filter(Boolean);
  } catch {
    return [];
  }
};

// The native createForumTopic action only works once the gateway restarted
